def m(
    slot: str,
    title: str,
    ingredients: list[str],
    reason: str,
    cal: int,
    p: int,
    c: int,
    f: int,
    allergens: list[str],
    *,
    prep="10 mins",
    cook="15 mins",
    difficulty="Easy",
    instructions=None,
    budget="low",
    cuisine="indian",
    diabetes=True,
    pcos=True,
    swaps=None,
):
    return {
        "name": f"{slot}: {title}",
        "ingredients": ingredients,
        "reason": reason,
        "prep_time": prep,
        "cook_time": cook,
        "difficulty": difficulty,
        "instructions": instructions or [
            "Prep ingredients as listed.",
            "Cook using a small amount of oil or steam.",
            "Serve immediately.",
        ],
        "nutrition": {"calories": cal, "protein_g": p, "carbs_g": c, "fats_g": f},
        "allergens": allergens,
        "budget": budget,
        "cuisine": cuisine,
        "diabetes_friendly": diabetes,
        "pcos_friendly": pcos,
        "swaps": swaps or {},
    }


